// Full Date Translator e.g. "Monday, 21 September 2026"
export function translateFullDate(dateStr = '', lang = 'en') {
  if (lang === 'en' || !dateStr) return dateStr;
  let res = dateStr;
  // Replace day names
  const days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  for (const d of days) {
    if (res.includes(d)) {
      res = res.replace(new RegExp(d, 'g'), translateDayName(d, lang));
    }
  }
  // Replace month names
  const months = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  for (const m of months) {
    if (res.includes(m)) {
      res = res.replace(new RegExp(m, 'g'), translateMonthName(m, lang));
    }
  }
  return res;
}
